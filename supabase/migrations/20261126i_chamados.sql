-- =====================================================================
-- ETAPA 5 do ERP: CHAMADOS DE SUPORTE (tela /suporte)
--   - o cliente abre um chamado (sem sinal, equipamento, plataforma, financeiro...) e conversa com a equipe
--   - a equipe (ADM e funcionário) responde, deixa nota interna, muda prioridade e responsável
--   - quando precisa de visita, o chamado vira OS (pré-OS do fluxo que já existe)
--   - OS finalizada → chamado resolvido sozinho, com aviso ao cliente
--   - avisos no sino (fv_notificacoes) para os dois lados
-- Rode uma vez no Supabase: SQL Editor > New query > colar tudo > Run. Pode rodar de novo.
-- Precisa de: fv_papel()/fv_eh_admin() (20261124e), fv_notificacoes (20261126b),
--             ordens_servico.status e solicitacoes_servico.os_id (20261124c).
-- =====================================================================

-- Empresa do usuário logado (cliente)
create or replace function public.fv_empresa_do_usuario()
returns text language sql stable security definer set search_path = public as $$
  select empresa_id::text from public.profiles where id = auth.uid()
$$;
grant execute on function public.fv_empresa_do_usuario() to authenticated;

-- 1) Chamados ------------------------------------------------------------
do $$
declare tipo_emp text; tipo_vei text; tipo_sol text;
begin
  select format_type(a.atttypid, a.atttypmod) into tipo_emp from pg_attribute a where a.attrelid = 'public.empresas'::regclass and a.attname = 'id';
  select format_type(a.atttypid, a.atttypmod) into tipo_vei from pg_attribute a where a.attrelid = 'public.veiculos'::regclass and a.attname = 'id';
  select format_type(a.atttypid, a.atttypmod) into tipo_sol from pg_attribute a where a.attrelid = 'public.solicitacoes_servico'::regclass and a.attname = 'id';
  execute format($f$
    create table if not exists public.chamados (
      id                    uuid primary key default gen_random_uuid(),
      numero                integer generated by default as identity unique,
      empresa_id            %s not null references public.empresas(id) on delete cascade,
      veiculo_id            %s references public.veiculos(id) on delete set null,
      categoria             text not null default 'OUTRO',     -- SEM_SINAL, EQUIPAMENTO, PLATAFORMA, FINANCEIRO, INSTALACAO, OUTRO
      prioridade            text not null default 'NORMAL',    -- BAIXA, NORMAL, ALTA, URGENTE
      titulo                text not null,
      descricao             text,
      status                text not null default 'ABERTO',    -- ABERTO, EM_ATENDIMENTO, AGUARDANDO_CLIENTE, VIROU_OS, RESOLVIDO, FECHADO
      aberto_por            uuid default auth.uid(),
      aberto_por_nome       text,
      aberto_pela_equipe    boolean not null default false,
      responsavel_id        uuid,
      responsavel_nome      text,
      os_id                 uuid references public.ordens_servico(id) on delete set null,
      solicitacao_id        %s references public.solicitacoes_servico(id) on delete set null,
      primeira_resposta_em  timestamptz,
      resolvido_em          timestamptz,
      ultima_msg_em         timestamptz not null default now(),
      ultima_msg_de         text,                              -- CLIENTE ou EQUIPE (quem falou por último)
      avaliacao             smallint check (avaliacao between 1 and 5),
      avaliacao_comentario  text,
      created_at            timestamptz not null default now(),
      updated_at            timestamptz not null default now()
    )$f$, tipo_emp, tipo_vei, tipo_sol);
end $$;
create index if not exists chamados_empresa_idx on public.chamados (empresa_id, created_at desc);
create index if not exists chamados_status_idx on public.chamados (status);
create index if not exists chamados_os_idx on public.chamados (os_id);

create table if not exists public.chamado_mensagens (
  id          uuid primary key default gen_random_uuid(),
  chamado_id  uuid not null references public.chamados(id) on delete cascade,
  autor_id    uuid default auth.uid(),
  autor_nome  text,
  autor_tipo  text not null default 'CLIENTE',   -- CLIENTE, EQUIPE, SISTEMA
  texto       text not null,
  interno     boolean not null default false,    -- nota só da equipe
  anexos      jsonb not null default '[]'::jsonb, -- [{ path, nome, tipo }] no bucket "chamados"
  created_at  timestamptz not null default now()
);
create index if not exists chamado_mensagens_idx on public.chamado_mensagens (chamado_id, created_at);

-- 2) Regras ao abrir e ao mudar -----------------------------------------------
create or replace function public.fv_chamado_antes()
returns trigger language plpgsql security definer set search_path = public as $$
declare equipe boolean := coalesce(public.fv_papel(), '') in ('admin', 'funcionario');
begin
  if tg_op = 'INSERT' then
    new.aberto_por := auth.uid();
    new.aberto_por_nome := coalesce((select username from public.profiles where id = auth.uid()), new.aberto_por_nome, 'Cliente');
    new.aberto_pela_equipe := equipe;
    if not equipe and auth.uid() is not null then
      new.status := 'ABERTO';
      new.responsavel_id := null; new.responsavel_nome := null; new.os_id := null; new.solicitacao_id := null;
      new.avaliacao := null;
      if new.prioridade not in ('BAIXA', 'NORMAL', 'ALTA') then new.prioridade := 'NORMAL'; end if;
    end if;
    new.ultima_msg_de := case when equipe then 'EQUIPE' else 'CLIENTE' end;
  else
    if new.responsavel_id is distinct from old.responsavel_id then
      new.responsavel_nome := (select username from public.profiles where id = new.responsavel_id);
    end if;
    if new.status in ('RESOLVIDO', 'FECHADO') and old.status not in ('RESOLVIDO', 'FECHADO') then new.resolvido_em := now(); end if;
    if new.status not in ('RESOLVIDO', 'FECHADO') then new.resolvido_em := null; end if;
  end if;
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists fv_chamado_antes on public.chamados;
create trigger fv_chamado_antes before insert or update on public.chamados
  for each row execute function public.fv_chamado_antes();

-- Quem deve receber os avisos
create or replace function public.fv_chamado_equipe()
returns uuid[] language sql stable security definer set search_path = public as $$
  select coalesce(array_agg(id), '{}') from public.profiles where role in ('admin', 'funcionario')
$$;
create or replace function public.fv_chamado_clientes(p_empresa text)
returns uuid[] language sql stable security definer set search_path = public as $$
  select coalesce(array_agg(id), '{}') from public.profiles where empresa_id::text = p_empresa and coalesce(role, 'cliente') = 'cliente'
$$;

create or replace function public.fv_chamado_avisos()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  cli text := (select nome from public.empresas where id = new.empresa_id);
  rotulo text := '#' || new.numero || ' ' || new.titulo;
begin
  if tg_op = 'INSERT' then
    if new.aberto_pela_equipe then
      perform public.fv_notificar(public.fv_chamado_clientes(new.empresa_id::text), 'Chamado aberto pela Full Vision', rotulo, '/suporte?c=' || new.id);
    else
      perform public.fv_notificar(public.fv_chamado_equipe(),
        case when new.prioridade in ('ALTA', 'URGENTE') then 'Chamado ' || lower(new.prioridade) || ' de ' || cli else 'Novo chamado de ' || cli end,
        rotulo, '/suporte?c=' || new.id);
    end if;
    return null;
  end if;
  if new.status is distinct from old.status then
    if new.status in ('RESOLVIDO', 'VIROU_OS', 'AGUARDANDO_CLIENTE') then
      perform public.fv_notificar(public.fv_chamado_clientes(new.empresa_id::text),
        case new.status when 'RESOLVIDO' then 'Chamado resolvido' when 'VIROU_OS' then 'Visita técnica agendada' else 'Chamado aguardando sua resposta' end,
        rotulo, '/suporte?c=' || new.id);
    end if;
  end if;
  if new.responsavel_id is distinct from old.responsavel_id and new.responsavel_id is not null then
    perform public.fv_notificar(array[new.responsavel_id], 'Chamado passado para você', rotulo || ' (' || coalesce(cli, '') || ')', '/suporte?c=' || new.id);
  end if;
  return null;
end $$;
drop trigger if exists fv_chamado_avisos on public.chamados;
create trigger fv_chamado_avisos after insert or update of status, responsavel_id on public.chamados
  for each row execute function public.fv_chamado_avisos();

-- Mensagem: autor preenchido pelo banco, mexe no status e avisa o outro lado
create or replace function public.fv_chamado_msg_antes()
returns trigger language plpgsql security definer set search_path = public as $$
declare equipe boolean := coalesce(public.fv_papel(), '') in ('admin', 'funcionario');
begin
  if new.autor_tipo = 'SISTEMA' and (equipe or auth.uid() is null or current_setting('fv.sistema', true) = '1') then
    new.autor_nome := coalesce(new.autor_nome, 'Sistema');
    return new;
  end if;
  new.autor_id := auth.uid();
  new.autor_nome := coalesce((select username from public.profiles where id = auth.uid()), 'Usuário');
  new.autor_tipo := case when equipe then 'EQUIPE' else 'CLIENTE' end;
  if not equipe then new.interno := false; end if;
  return new;
end $$;
drop trigger if exists fv_chamado_msg_antes on public.chamado_mensagens;
create trigger fv_chamado_msg_antes before insert on public.chamado_mensagens
  for each row execute function public.fv_chamado_msg_antes();

create or replace function public.fv_chamado_msg_depois()
returns trigger language plpgsql security definer set search_path = public as $$
declare c public.chamados%rowtype; rotulo text;
begin
  if new.interno or new.autor_tipo = 'SISTEMA' then return null; end if;
  select * into c from public.chamados where id = new.chamado_id;
  rotulo := '#' || c.numero || ' ' || c.titulo;
  if new.autor_tipo = 'CLIENTE' then
    update public.chamados set ultima_msg_em = now(), ultima_msg_de = 'CLIENTE',
      status = case when status in ('AGUARDANDO_CLIENTE', 'RESOLVIDO') then 'ABERTO' else status end
     where id = c.id;
    perform public.fv_notificar(case when c.responsavel_id is not null then array[c.responsavel_id] else public.fv_chamado_equipe() end,
      'Cliente respondeu', rotulo || ': ' || left(new.texto, 120), '/suporte?c=' || c.id);
  else
    update public.chamados set ultima_msg_em = now(), ultima_msg_de = 'EQUIPE',
      primeira_resposta_em = coalesce(primeira_resposta_em, now()),
      status = case when status = 'ABERTO' then 'EM_ATENDIMENTO' else status end,
      responsavel_id = coalesce(responsavel_id, auth.uid())
     where id = c.id;
    perform public.fv_notificar(public.fv_chamado_clientes(c.empresa_id::text), 'Resposta no seu chamado', rotulo || ': ' || left(new.texto, 120), '/suporte?c=' || c.id);
  end if;
  return null;
end $$;
drop trigger if exists fv_chamado_msg_depois on public.chamado_mensagens;
create trigger fv_chamado_msg_depois after insert on public.chamado_mensagens
  for each row execute function public.fv_chamado_msg_depois();

-- 3) OS finalizada → chamado resolvido --------------------------------------
create or replace function public.fv_os_resolve_chamado()
returns trigger language plpgsql security definer set search_path = public as $$
declare c record;
begin
  if new.status = 'finalizada' and old.status is distinct from 'finalizada' then
    perform set_config('fv.sistema', '1', true);
    for c in select id from public.chamados where os_id = new.id and status not in ('RESOLVIDO', 'FECHADO') loop
      update public.chamados set status = 'RESOLVIDO' where id = c.id;
      insert into public.chamado_mensagens (chamado_id, autor_tipo, autor_nome, texto)
      values (c.id, 'SISTEMA', 'Sistema', 'A visita técnica foi concluída e a OS foi finalizada. Se o problema continuar, é só responder aqui que o chamado reabre.');
    end loop;
    perform set_config('fv.sistema', '', true);
  end if;
  return null;
end $$;
drop trigger if exists fv_os_resolve_chamado on public.ordens_servico;
create trigger fv_os_resolve_chamado after update of status on public.ordens_servico
  for each row execute function public.fv_os_resolve_chamado();

-- 4) Cliente fecha / avalia / reabre (a única mudança que ele pode fazer) ------
create or replace function public.fv_chamado_cliente_acao(p_chamado uuid, p_acao text, p_nota smallint default null, p_comentario text default null)
returns void language plpgsql security definer set search_path = public as $$
declare c public.chamados%rowtype;
begin
  select * into c from public.chamados where id = p_chamado;
  if not found or c.empresa_id::text is distinct from public.fv_empresa_do_usuario() then raise exception 'Chamado não encontrado.'; end if;
  if p_acao = 'FECHAR' then
    update public.chamados set status = 'FECHADO', avaliacao = coalesce(p_nota, avaliacao), avaliacao_comentario = coalesce(nullif(trim(p_comentario), ''), avaliacao_comentario) where id = c.id;
    perform public.fv_notificar(public.fv_chamado_equipe(), 'Cliente fechou o chamado',
      '#' || c.numero || ' ' || c.titulo || coalesce(' · nota ' || p_nota, ''), '/suporte?c=' || c.id);
  elsif p_acao = 'AVALIAR' then
    update public.chamados set avaliacao = p_nota, avaliacao_comentario = nullif(trim(p_comentario), '') where id = c.id;
  elsif p_acao = 'REABRIR' then
    update public.chamados set status = 'ABERTO' where id = c.id;
    perform public.fv_notificar(public.fv_chamado_equipe(), 'Chamado reaberto pelo cliente', '#' || c.numero || ' ' || c.titulo, '/suporte?c=' || c.id);
  else
    raise exception 'Ação inválida.';
  end if;
end $$;
grant execute on function public.fv_chamado_cliente_acao(uuid, text, smallint, text) to authenticated;

-- 5) Acesso -----------------------------------------------------------------
alter table public.chamados enable row level security;
alter table public.chamado_mensagens enable row level security;

drop policy if exists "chamados equipe" on public.chamados;
create policy "chamados equipe" on public.chamados for all to authenticated
  using (public.fv_papel() in ('admin', 'funcionario')) with check (public.fv_papel() in ('admin', 'funcionario'));
drop policy if exists "chamados cliente ve" on public.chamados;
create policy "chamados cliente ve" on public.chamados for select to authenticated
  using (empresa_id::text = public.fv_empresa_do_usuario());
drop policy if exists "chamados cliente abre" on public.chamados;
create policy "chamados cliente abre" on public.chamados for insert to authenticated
  with check (coalesce(public.fv_papel(), 'cliente') = 'cliente' and empresa_id::text = public.fv_empresa_do_usuario());

drop policy if exists "mensagens equipe" on public.chamado_mensagens;
create policy "mensagens equipe" on public.chamado_mensagens for all to authenticated
  using (public.fv_papel() in ('admin', 'funcionario')) with check (public.fv_papel() in ('admin', 'funcionario'));
drop policy if exists "mensagens cliente ve" on public.chamado_mensagens;
create policy "mensagens cliente ve" on public.chamado_mensagens for select to authenticated
  using (not interno and exists (select 1 from public.chamados c where c.id = chamado_id and c.empresa_id::text = public.fv_empresa_do_usuario()));
drop policy if exists "mensagens cliente escreve" on public.chamado_mensagens;
create policy "mensagens cliente escreve" on public.chamado_mensagens for insert to authenticated
  with check (not interno and exists (select 1 from public.chamados c where c.id = chamado_id and c.empresa_id::text = public.fv_empresa_do_usuario()));

-- 6) Fotos e anexos (bucket privado "chamados", pasta = id do chamado) ---------
insert into storage.buckets (id, name, public) values ('chamados', 'chamados', false) on conflict (id) do nothing;
drop policy if exists "chamados anexos" on storage.objects;
create policy "chamados anexos" on storage.objects for all to authenticated
  using (bucket_id = 'chamados' and (
    public.fv_papel() in ('admin', 'funcionario')
    or exists (select 1 from public.chamados c where c.id::text = split_part(name, '/', 1) and c.empresa_id::text = public.fv_empresa_do_usuario())))
  with check (bucket_id = 'chamados' and (
    public.fv_papel() in ('admin', 'funcionario')
    or exists (select 1 from public.chamados c where c.id::text = split_part(name, '/', 1) and c.empresa_id::text = public.fv_empresa_do_usuario())));
